guard CommandLine.arguments.count == 3 else {
    fputs("usage: generate_jp_options_font.swift OUTPUT_HEADER FONT_FILE\n", stderr)
    exit(2)
}

let output = CommandLine.arguments[1]
let fontPath = CommandLine.arguments[2]
let cellWidth = 12
let cellHeight = 14
let fontURL = URL(fileURLWithPath: fontPath)
guard FileManager.default.fileExists(atPath: fontPath),
      let provider = CGDataProvider(url: fontURL as CFURL),
      let graphicsFont = CGFont(provider),
      let postScriptName = graphicsFont.postScriptName as String? else {
    fputs("unable to load font file: \(fontPath)\n", stderr)
    exit(2)
}
CTFontManagerRegisterFontsForURL(fontURL as CFURL, .process, nil)
guard let font = NSFont(name: postScriptName, size: 12.0) else {
    fputs("unable to register font: \(postScriptName)\n", stderr)
    exit(2)
}

let characters = Array(Set(phrases.joined())).sorted { lhs, rhs in
    String(lhs).unicodeScalars.first!.value < String(rhs).unicodeScalars.first!.value
}

func glyphRows(for character: Character) -> [UInt16] {
    let rep = NSBitmapImageRep(
        bitmapDataPlanes: nil,
        pixelsWide: cellWidth,
        pixelsHigh: cellHeight,
        bitsPerSample: 8,
        samplesPerPixel: 4,
        hasAlpha: true,
        isPlanar: false,
        colorSpaceName: .deviceRGB,
        bytesPerRow: cellWidth * 4,
        bitsPerPixel: 32
    )!
    rep.size = NSSize(width: cellWidth, height: cellHeight)
    NSGraphicsContext.saveGraphicsState()
    NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: rep)
    NSColor.clear.setFill()
    NSRect(x: 0, y: 0, width: cellWidth, height: cellHeight).fill()
    let text = String(character) as NSString
    let attributes: [NSAttributedString.Key: Any] = [
        .font: font,
        .foregroundColor: NSColor.white
    ]
    let bounds = text.boundingRect(with: NSSize(width: 32, height: 32),
                                   options: [.usesLineFragmentOrigin],
                                   attributes: attributes)
    let x = floor((CGFloat(cellWidth) - bounds.width) * 0.5)
    text.draw(at: NSPoint(x: x, y: -1), withAttributes: attributes)
    NSGraphicsContext.restoreGraphicsState()

    var rows = [UInt16](repeating: 0, count: cellHeight)
    for y in 0..<cellHeight {
        var row: UInt16 = 0
        for x in 0..<cellWidth {
            if (rep.colorAt(x: x, y: y)?.alphaComponent ?? 0) >= 0.18 {
                row |= UInt16(1 << (cellWidth - 1 - x))
            }
        }
        rows[y] = row
    }
    return rows
}

var text = """
// Generated by tools/generate_jp_options_font.swift.
// Compact 12x14 glyph subset for the Japanese Options framebuffer overlay.
// Source font: \(fontURL.lastPathComponent), licensed separately under SIL OFL 1.1.
#pragma once
#include "3ds/types.h"

typedef struct {
    u32 codepoint;
    u16 rows[14];
} JpOptionsGlyph;

static const JpOptionsGlyph gJpOptionsGlyphs[] = {
"""

for character in characters {
    let scalar = String(character).unicodeScalars.first!.value
    let rows = glyphRows(for: character)
    let data = rows.map { String(format: "0x%03X", $0) }.joined(separator: ", ")
    text += String(format: "    { 0x%04X, { %@ } },\n", scalar, data)
}

text += """
};

#define JP_OPTIONS_GLYPH_COUNT (sizeof(gJpOptionsGlyphs) / sizeof(gJpOptionsGlyphs[0]))
#define JP_OPTIONS_GLYPH_WIDTH 12
#define JP_OPTIONS_GLYPH_HEIGHT 14
"""

try text.write(toFile: output, atomically: true, encoding: .utf8)
print("generated \(characters.count) glyphs from \(postScriptName) at \(output)")
