    "X軸反転", "Y軸反転", "両軸反転", "移動速度", "前転速度", "前転後の硬直",
    "+10%", "+20%", "-10%", "-20%",
    "L注目の操作方法を設定します。", "一人称視点の上下操作を設定します。",
    "一人称視点でジャイロ操作を使います。", "ゲーム画面のHUDサイズを設定します。",
    "探索時のカメラ距離を設定します。", "右スティックのカメラ操作を設定します。",
